REASONING_LOOP = (
    "1. 承诺：先把用户当前要求转成可交付结果和成功判据，不追加未要求的任务。",
    "2. 建模：区分已知事实、记忆线索、推断和未知；记住证据来源与时效。",
    "3. 选择下一步：找出最影响结论的未知，只选择最可能消除它的动作。",
    "4. 预期信息增益：行动前明确什么结果会支持、反驳或区分候选；"
    "若任何结果都不会改变判断，该行动没有价值。",
    "5. 观察与更新：将实际结果与预期比较，更新已知、未知和候选，而不是只记录动作成功。",
    "6. 收敛检查：无法指出仍缺的具体事实、同一未知没有缩小、或只剩低价值重复时，停止取证。",
    "7. 选择终态：证据足够就回答；缺少用户才能提供的信息就提问；"
    "能力或证据不足就 partial/blocked；资源上限只作最后安全边界。",
)


def cognitive_protocol_prompt() -> str:
    actions = "；".join(
        f"{operator}={OPERATOR_ACTIONS[operator]}"
        for operator in OPERATOR_LIBRARY
    )
    contrasts = "；".join(
        f"{operator}={CONTRAST_CHECKS[operator]}"
        for operator in OPERATOR_LIBRARY
    )
    return (
        "认知自主契约（由模型自主判断，不使用固定算子路由）：\n"
        "- 内部执行以下推理循环，不输出逐步思维链：\n"
        + "\n".join(f"  {step}" for step in REASONING_LOOP)
        + "\n"
        "- 先判断当前究竟要理解、决定、修复、验证、安慰还是收束；"
        "不要因为任务类别相似就机械套用相同思路。\n"
        "- 可用的人类思维视角："
        + "、".join(OPERATOR_LIBRARY)
        + "。可自行选择 0-4 个，也可以组合或不用。\n"
        f"- 视角执行参考：{actions}。\n"
        f"- 反向复核参考：{contrasts}。\n"
        "- 必须遵守："
        + "；".join(COGNITIVE_INVARIANTS)
        + "。\n"
        "- 内部思考不需要展示，也不要为了证明思考而扩写；"
        "输出只保留结论、必要依据和实际动作。"
    )
